"""Generate docs/EVALUATION.md from reports/ only. Nothing in the output is typed by hand."""
from __future__ import annotations

import glob
import json
from pathlib import Path


def latest(exp: str) -> dict | None:
    files = sorted(glob.glob(f'reports/{exp}/*.json'))
    return json.loads(Path(files[-1]).read_text()) if files else None


def pct(m: dict) -> str:
    return f'{m["mean"]:.3f} [{m["low"]:.3f}, {m["high"]:.3f}] (n={m["n_items"]})'


def section_e2(d: dict) -> list[str]:
    out = ['| category | attempts | oracle-confirmed ASR | judge-flagged (unverified) '
           '| thin sample |', '|---|---|---|---|---|']
    for c, v in d['categories'].items():
        out.append(f'| {c} | {v["attempts"]} | {pct(v["asr"])} | {v["judge_flagged"]} | '
                   f'{v["thin_sample"]} |')
    out += ['', f'Overall: {pct(d["overall_asr"])}; truncated: {d["truncated"]}; '
            f'notional LLM cost: {d["cost_usd"]:.4f} USD.']
    return out


def section_e3(d: dict) -> list[str]:
    out = [f'Parity {pct(d["parity_rate"])}; compared {d["n_compared"]}, '
           f'errors {d["n_errors"]}.', '', '| item | field | evaluated | served |',
           '|---|---|---|---|']
    out += [f'| {m["item_id"]} | {m["field"]} | {m["evaluated"]} | {m["served"]} |'
            for m in d['mismatches']]
    return out


def generic(d: dict) -> list[str]:
    return ['```json', json.dumps(d, indent=1, default=str)[:2500], '```']


TITLES = {'e1': 'E1 Unsafe challenger blocked', 'e2': 'E2 Baseline red team of the endpoint',
          'e3': 'E3 Serving parity (held-out split)', 'e4': 'E4 Injected regression detected',
          'e5': 'E5 Trace-driven improvement', 'e6': 'E6 Durable approvals',
          'e7': 'E7 Containment'}


def main() -> None:
    lines = ['# Evaluation', '',
             'Generated by `python -m scripts.make_evaluation` from `reports/`. Synthetic data; '
             'LLM cost is notional; nothing here is a production claim.', '']
    for exp, title in TITLES.items():
        lines += [f'## {title}', '']
        d = latest(exp)
        if d is None:
            lines += ['_Not run._', '']
            continue
        body = {'e2': section_e2, 'e3': section_e3}.get(exp, generic)(d)
        lines += body + ['']
    Path('docs/EVALUATION.md').write_text('\n'.join(lines))
    print('wrote docs/EVALUATION.md')


if __name__ == '__main__':
    main()
